create table public.settings (
  id bigint generated by default as identity primary key,
  business_name text not null default 'Mi negocio' check (btrim(business_name) <> ''),
  description text,
  phone text,
  whatsapp text,
  address text,
  currency text not null default 'MXN',
  ordering_enabled boolean not null default false,
  delivery_enabled boolean not null default false,
  pickup_enabled boolean not null default true,
  delivery_fee numeric(10,2) not null default 0 check (delivery_fee >= 0),
  min_order_amount numeric(10,2) not null default 0 check (min_order_amount >= 0),
  cash_enabled boolean not null default true,
  transfer_enabled boolean not null default false,
  transfer_bank text,
  transfer_holder text,
  transfer_account text,
  delivery_eta_minutes integer not null default 45 check (delivery_eta_minutes between 1 and 240),
  pickup_eta_minutes integer not null default 20 check (pickup_eta_minutes between 1 and 240),
  business_hours_enabled boolean not null default false,
  business_timezone text not null default 'America/Mexico_City' check (btrim(business_timezone) <> ''),
  schedule jsonb not null default '{}'::jsonb check (jsonb_typeof(schedule) = 'object'),
  delivery_neighborhoods jsonb not null default '[]'::jsonb check (jsonb_typeof(delivery_neighborhoods) = 'array'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Esta aplicación administra un solo negocio y espera una fila en settings.
create unique index settings_single_row_idx on public.settings ((true));

create table public.categories (
  id bigint generated by default as identity primary key,
