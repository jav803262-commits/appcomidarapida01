  price numeric(10,2) not null check (price >= 0),
  image_url text,
  emoji text,
  available boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.product_extras (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  name text not null check (btrim(name) <> ''),
  price numeric(10,2) not null default 0 check (price >= 0),
  available boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique
    check (order_number ~ '^[A-HJ-NP-Z2-9]{6}$'),
  client_request_id uuid not null unique,
  request_fingerprint text not null check (request_fingerprint ~ '^[0-9a-f]{32}$'),
  customer_name text not null check (btrim(customer_name) <> ''),
  customer_phone text not null check (customer_phone ~ '^[0-9]{10}$'),
  order_type text not null check (order_type in ('pickup', 'delivery')),
  payment_method text not null check (payment_method in ('cash', 'transfer')),
  cash_amount numeric(10,2),
  subtotal numeric(10,2) not null check (subtotal >= 0),
  delivery_fee numeric(10,2) not null default 0 check (delivery_fee >= 0),
  total numeric(10,2) not null check (total > 0),
  address jsonb,
  notes text,
  status text not null default 'pending'
    check (status in ('pending', 'confirmed', 'preparing', 'ready', 'delivered', 'cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint orders_address_shape check (address is null or jsonb_typeof(address) = 'object'),
  constraint orders_address_matches_type check (
    (order_type = 'pickup' and address is null)
    or (order_type = 'delivery' and address is not null)
  ),
  constraint orders_total_consistency check (total = subtotal + delivery_fee),
  constraint orders_notes_length check (notes is null or char_length(notes) <= 1000),
  constraint orders_payment_cash_consistency check (
    (payment_method = 'cash' and cash_amount is not null and cash_amount >= total)
    or (payment_method = 'transfer' and cash_amount is null)
  )
);

-- Libro de pagos: no se infiere el pago a partir de orders.payment_method.
-- Un pedido admite como máximo un pago activo; los reversos conservan historial.
create table public.order_payments (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete restrict,
  method text not null check (method in ('cash', 'transfer')),
  amount numeric(10,2) not null check (amount > 0),
  cash_tendered numeric(10,2),
  change_due numeric(10,2) not null default 0 check (change_due >= 0),
  reference text,
  status text not null default 'active' check (status in ('active', 'reversed')),
  received_by uuid references auth.users(id) on delete set null,
  paid_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  constraint order_payments_cash_fields check (
    (method = 'cash' and cash_tendered is not null and cash_tendered >= amount
      and change_due = cash_tendered - amount and reference is null)
    or
    (method = 'transfer' and cash_tendered is null and change_due = 0
      and nullif(btrim(coalesce(reference, '')), '') is not null)
  )
);

create index idx_order_payments_order_paid_at
  on public.order_payments(order_id, paid_at desc);
create unique index uq_order_payments_one_active_per_order
  on public.order_payments(order_id)
  where status = 'active';

create table public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null check (btrim(product_name) <> ''),
  unit_price numeric(10,2) not null check (unit_price >= 0),
  quantity integer not null check (quantity between 1 and 50),
  extras jsonb not null default '[]'::jsonb check (jsonb_typeof(extras) = 'array'),
  subtotal numeric(10,2) not null check (subtotal >= 0),
  created_at timestamptz not null default now()
);

-- Vista pública mínima para consultar el estado sin exponer la tabla orders.
