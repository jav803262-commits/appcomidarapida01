create function public.business_is_open(p_settings public.settings)
returns boolean
language plpgsql
stable
security definer
set search_path = pg_catalog, pg_temp
as $function$
declare
  v_local timestamp;
  v_day text;
  v_day_config jsonb;
  v_now_time time;
  v_open time;
  v_close time;
begin
  if not coalesce(p_settings.business_hours_enabled, false) then
    return true;
  end if;

  v_local := now() at time zone coalesce(nullif(p_settings.business_timezone, ''), 'America/Mexico_City');
  v_day := case extract(isodow from v_local)::integer
    when 1 then 'monday'
    when 2 then 'tuesday'
    when 3 then 'wednesday'
    when 4 then 'thursday'
    when 5 then 'friday'
    when 6 then 'saturday'
    else 'sunday'
  end;
  v_day_config := coalesce(p_settings.schedule -> v_day, '{}'::jsonb);

  if coalesce((v_day_config ->> 'enabled')::boolean, false) is not true then
    return false;
  end if;

  v_now_time := v_local::time;
  v_open := nullif(v_day_config ->> 'open', '')::time;
  v_close := nullif(v_day_config ->> 'close', '')::time;

  if v_open is null or v_close is null or v_open >= v_close then
    return false;
  end if;

  return v_now_time >= v_open and v_now_time < v_close;
exception when others then
  -- Una configuración horaria inválida nunca debe abrir pedidos por accidente.
  return false;
end;
$function$;

create function public.validate_delivery_neighborhood()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, pg_temp
as $function$
declare
  v_neighborhood text;
  v_allowed jsonb;
begin
  if new.order_type <> 'delivery' then
    return new;
  end if;

  v_neighborhood := nullif(btrim(coalesce(new.address ->> 'neighborhood', '')), '');
  select s.delivery_neighborhoods
    into v_allowed
    from public.settings s
    order by s.id
    limit 1;

  if v_neighborhood is null or v_allowed is null or jsonb_typeof(v_allowed) <> 'array' then
    raise exception using errcode = 'P0001',
      message = 'No realizamos entregas en esa colonia. Selecciona una colonia disponible.';
  end if;

  if jsonb_array_length(v_allowed) = 0 or not exists (
    select 1
    from jsonb_array_elements_text(v_allowed) as allowed(name)
    where lower(btrim(allowed.name)) = lower(v_neighborhood)
  ) then
    raise exception using errcode = 'P0001',
      message = 'No realizamos entregas en esa colonia. Selecciona una colonia disponible.';
  end if;

  return new;
end;
$function$;

