create function public.sync_public_order_tracking()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, pg_temp
as $function$
declare
  v_eta integer;
begin
  select case when new.order_type = 'delivery'
    then coalesce(s.delivery_eta_minutes, 45)
    else coalesce(s.pickup_eta_minutes, 20)
  end
  into v_eta
  from public.settings s
  order by s.id
  limit 1;

  insert into public.public_order_tracking (
    order_id, order_number, status, created_at, estimated_minutes, updated_at, phone_last4
  ) values (
    new.id,
    new.order_number,
    new.status,
    new.created_at,
    greatest(1, least(coalesce(v_eta, 30), 240)),
    now(),
    right(new.customer_phone, 4)
  )
  on conflict (order_id) do update set
    order_number = excluded.order_number,
    status = excluded.status,
    created_at = excluded.created_at,
    estimated_minutes = excluded.estimated_minutes,
    phone_last4 = excluded.phone_last4,
    updated_at = now();

  return new;
end;
$function$;

create trigger orders_sync_public_tracking_insert
 after insert on public.orders
 for each row execute function public.sync_public_order_tracking();

create trigger orders_sync_public_tracking_update
 after update of order_number, status, created_at, order_type, customer_phone on public.orders
 for each row execute function public.sync_public_order_tracking();

