create function public.record_order_payment(
  p_order_id uuid,
  p_method text,
  p_confirm_method_change boolean default false,
  p_transfer_verified boolean default false,
  p_reference text default null,
  p_cash_tendered numeric default null
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, pg_temp
as $function$
declare
  v_order public.orders%rowtype;
  v_payment public.order_payments%rowtype;
  v_reference text;
  v_change numeric(10,2);
begin
  if not public.is_admin() then
    raise exception using errcode = '42501', message = 'No tienes permiso para registrar pagos.';
  end if;
  if p_order_id is null then
    raise exception using errcode = '22004', message = 'Falta el identificador del pedido.';
  end if;
  if p_method is null or p_method not in ('cash', 'transfer') then
    raise exception using errcode = '22023', message = 'Método de pago inválido.';
  end if;

  -- El bloqueo del pedido serializa dos intentos simultáneos de cobro.
  select o.* into v_order
  from public.orders o
  where o.id = p_order_id
  for update;

  if not found then
    raise exception using errcode = 'P0002', message = 'No se encontró el pedido.';
  end if;
  if v_order.total <= 0 then
    raise exception using errcode = '23514', message = 'No se pueden cobrar pedidos con total cero.';
  end if;
  if v_order.status <> 'ready' then
    raise exception using errcode = 'P0001', message = 'Solo se puede cobrar un pedido que esté listo.';
  end if;
  if exists (
    select 1 from public.order_payments p
    where p.order_id = v_order.id and p.status = 'active'
  ) then
    raise exception using errcode = '23505', message = 'Este pedido ya tiene un pago activo; no se puede cobrar de nuevo.';
  end if;
  if v_order.payment_method <> p_method
     and coalesce(p_confirm_method_change, false) is not true then
    raise exception using errcode = 'P0001',
      message = 'El método de pago cambió. Confirma explícitamente el cambio para continuar.';
  end if;

  if p_method = 'cash' then
    if p_cash_tendered is null or p_cash_tendered < v_order.total then
      raise exception using errcode = 'P0001', message = 'El efectivo recibido debe ser igual o mayor al total.';
    end if;
    if p_cash_tendered <= 0 then
      raise exception using errcode = 'P0001', message = 'El efectivo recibido debe ser mayor que cero.';
    end if;
    if p_reference is not null and btrim(p_reference) <> '' then
      raise exception using errcode = '22023', message = 'No envíes referencia para un pago en efectivo.';
    end if;
    v_change := round(p_cash_tendered - v_order.total, 2);
    v_reference := null;
  else
    if coalesce(p_transfer_verified, false) is not true then
      raise exception using errcode = 'P0001',
        message = 'Confirma que el dinero de la transferencia fue recibido antes de registrar el pago.';
    end if;
    v_reference := nullif(btrim(coalesce(p_reference, '')), '');
    if v_reference is null then
      raise exception using errcode = 'P0001',
        message = 'Registra la referencia o folio de la transferencia verificada.';
    end if;
    if length(v_reference) > 120 then
      raise exception using errcode = '22023', message = 'La referencia no puede superar 120 caracteres.';
    end if;
    if p_cash_tendered is not null then
      raise exception using errcode = '22023', message = 'No envíes efectivo recibido para una transferencia.';
    end if;
    v_change := 0;
  end if;

  -- Mantiene coherentes los campos heredados; order_payments es el comprobante.
  update public.orders
  set payment_method = p_method,
      cash_amount = case when p_method = 'cash' then p_cash_tendered else null end
  where id = v_order.id;

  insert into public.order_payments (
    order_id, method, amount, cash_tendered, change_due, reference, status, received_by
  ) values (
    v_order.id, p_method, v_order.total,
    case when p_method = 'cash' then p_cash_tendered else null end,
    v_change, v_reference, 'active', auth.uid()
  ) returning * into v_payment;

  return jsonb_build_object(
    'paymentId', v_payment.id,
    'orderId', v_payment.order_id,
    'method', v_payment.method,
    'amount', v_payment.amount,
    'cashTendered', v_payment.cash_tendered,
    'changeDue', v_payment.change_due,
    'reference', v_payment.reference,
    'status', v_payment.status,
    'paidAt', v_payment.paid_at
  );
end;
$function$;

create function public.transition_order_status(
  p_order_id uuid,
  p_new_status text
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, pg_temp
as $function$
declare
  v_order public.orders%rowtype;
  v_allowed boolean := false;
  v_previous_status text;
begin
  if not public.is_admin() then
    raise exception using errcode = '42501', message = 'No tienes permiso para cambiar el estado del pedido.';
  end if;
  if p_order_id is null or p_new_status is null then
    raise exception using errcode = '22004', message = 'Falta el pedido o el nuevo estado.';
  end if;
  if p_new_status not in ('confirmed', 'preparing', 'ready', 'delivered', 'cancelled') then
    raise exception using errcode = '22023', message = 'Estado de pedido no válido.';
  end if;

  select o.* into v_order
  from public.orders o
  where o.id = p_order_id
  for update;
  if not found then
    raise exception using errcode = 'P0002', message = 'No se encontró el pedido.';
  end if;

  v_previous_status := v_order.status;
  v_allowed := case
    when v_order.status = 'pending' and p_new_status in ('confirmed', 'cancelled') then true
    when v_order.status = 'confirmed' and p_new_status in ('preparing', 'cancelled') then true
    when v_order.status = 'preparing' and p_new_status = 'ready' then true
    when v_order.status = 'ready' and p_new_status = 'delivered' then true
    else false
  end;
  if not v_allowed then
    raise exception using errcode = 'P0001',
      message = format('Transición no permitida: %s -> %s.', v_order.status, p_new_status);
  end if;
  if p_new_status = 'delivered' and not exists (
    select 1 from public.order_payments p
    where p.order_id = v_order.id and p.status = 'active'
  ) then
    raise exception using errcode = 'P0001',
      message = 'No se puede marcar como entregado un pedido sin un pago activo registrado.';
  end if;

  update public.orders set status = p_new_status
  where id = v_order.id
  returning * into v_order;

  return jsonb_build_object(
    'orderId', v_order.id,
    'orderNumber', v_order.order_number,
    'previousStatus', v_previous_status,
    'status', v_order.status,
    'updatedAt', v_order.updated_at
  );
end;
$function$;

